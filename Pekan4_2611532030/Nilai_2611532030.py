# Buat program untuk nested if
# Nama variabel ditambah 4 digit terakhir nim terakhir contoh: ipk_1234
# Program ini menggunakan fungsi input()
# Program konversi nilai angka menjadi huruf

nilai_2030 = int(input("Inputkan nilai angka = "))

if nilai_2030 >= 81:
    print("A")
elif nilai_2030 >= 70:
    print ("B")
elif nilai_2030 >= 60:
    print("C")
elif nilai_2030 >= 50:
    print("D")
else:
    print("E")